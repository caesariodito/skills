import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parse, svg, selection } from './model.mjs';
const sample = readFileSync(new URL('./example.json', import.meta.url), 'utf8');
let input = sample;
let mkdirError = false, writeError = false, mkdirCalls = 0;
const writes = [];
const tasks = [];
const focus = {focus(){}, is_focused(){return true;}};
const cx = {focus_handle:()=>focus, timer:{every(){}}, spawn:fn=>tasks.push(fn), notify(){}, stop_propagation(){}};
const element = new Proxy(function(){}, {get:()=>element, apply:()=>element});
const source = readFileSync(new URL('./main.js', import.meta.url), 'utf8').replace(/^import .*;\n/gm, '').replace('export default class', 'return class');
const Viewer = new Function('View','div','image','v_flex','h_flex','TextView','props','theme','readTextFile','appHome','nextCommand','mkdir','writeFile','parse','svg','selection',source)(class {},element,element,element,element,{markdown:()=>element},()=>({file:'/synthetic/explanation.json'}),()=>({}),async()=>input,()=>'/synthetic-app',async()=>new Promise(()=>{}),async()=>{ mkdirCalls++; if (mkdirError) throw Error('cache directory unavailable'); },async(path, value)=>{ if (writeError) throw Error('cache write unavailable'); writes.push({path,value}); },parse,svg,selection);
const v = new Viewer();
v.init({},cx);
await tasks.shift()(cx); // Initial reload; command listener deliberately not run.
assert.equal(v.document.title,'Native spec explanations');
assert.ok(Object.keys(v.images).length === 2);
assert.doesNotThrow(()=>v.render(cx));
const key = k => v.key({key:k, modifiers:{}},cx);
key('right'); assert.equal(v.selected.scenario,'approve');
key('d'); assert.equal(v.details,true);
key('down'); assert.equal(v.selected.section,'failure'); assert.equal(v.details,false);
key('left'); assert.equal(v.selected.scenario,'missing');
v.width=350; assert.doesNotThrow(()=>v.render(cx));
input='{'; v.reload(cx); await tasks.pop()(cx);
assert.ok(v.error); assert.equal(v.document.title,'Native spec explanations');
input=null; v.reload(cx); await tasks.pop()(cx);
assert.ok(v.error.includes('missing')); assert.ok(v.document);
const next=JSON.parse(sample); next.title='Refreshed'; next.sections=next.sections.slice(0,1);
input=JSON.stringify(next); v.reload(cx); await tasks.pop()(cx);
assert.equal(v.error,''); assert.equal(v.document.title,'Refreshed');
assert.equal(v.selected.section,'overview');
assert.equal(v.selected.scenario,'explore');
key('r'); await tasks.pop()(cx); assert.equal(v.error,'');
// Cache failure never prevents otherwise valid text from loading.
mkdirError=true; input=sample; tasks.length=0;
const noCache=new Viewer(); noCache.init({},cx); await tasks.shift()(cx);
assert.ok(noCache.document); assert.equal(noCache.error,'');
assert.match(Object.values(noCache.images)[0].error,/directory unavailable/);
assert.doesNotThrow(()=>noCache.render(cx));
const textOnly=JSON.parse(sample);
for (const s of textOnly.sections) for (const v of s.scenarios) delete v.diagram;
input=JSON.stringify(textOnly); const calls=mkdirCalls; tasks.length=0;
const textView=new Viewer(); textView.init({},cx); await tasks.shift()(cx);
assert.ok(textView.document); assert.equal(mkdirCalls,calls);
mkdirError=false; input=sample; noCache.raw=null; noCache.reload(cx); await tasks.pop()(cx);
assert.equal(typeof Object.values(noCache.images)[0],'string');
writeError=true; noCache.raw=null; noCache.reload(cx); await tasks.pop()(cx);
assert.ok(noCache.document); assert.match(Object.values(noCache.images)[0].error,/write unavailable/);
writeError=false;
// Hyphen and case-distinct IDs must never alias filesystem asset paths.
const collisions=JSON.parse(sample);
const base=collisions.sections[0];
collisions.sections=[['a-b','c'],['a','b-c'],['A','B']].map(([id,scenario],i)=>({...structuredClone(base),id,scenarios:[{...structuredClone(base.scenarios[0]),id:scenario,body:`Body ${i}`}]}));
input=JSON.stringify(collisions); writes.length=0; noCache.raw=null; noCache.reload(cx); await tasks.pop()(cx);
assert.equal(new Set(writes.map(v=>v.path.toLowerCase())).size,3);
assert.equal(Object.keys(noCache.images).length,3);
console.log('view state, keyboard handlers, narrow render, cache isolation/fallback and reload recovery checks passed');
